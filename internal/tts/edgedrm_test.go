package tts

import (
	"testing"
	"time"
)

func TestGenerateEdgeTokenVectors(t *testing.T) {
	t.Parallel()
	tests := map[int64]string{
		0:          "52BC7A17B50DFEC9-28C4394775C8751CD2F6859C030C06DB1489ACAB3B3A7651831FC26895177ED6",
		1700000000: "2CD23A2CA0B2595A-F3C846C370E05F9CC83ACC5F995C5F5D87A4D0F14CE8936A0F902E64099E38A2",
		1760000000: "6D50DDDB91812C33-DD68EFB01898B0750C9797D51A5FF93471DFDAE6888A1039D532CBDCCE54545D",
		1761580800: "04BC219DF9B14D39-02ACFAA46F282BF3D7A0B9A15242DB60413E4E82E14772EDB58E792F4A2FB81C",
		1782576000: "750C9D14FD20A612-6AFCEC5375065B2BA96E59A5F99F57E4A6334FF7B5B107AD4D322860A984F9F0",
	}
	for unixSeconds, want := range tests {
		got := generateEdgeToken(time.Unix(unixSeconds, 0))
		if got != want {
			t.Errorf("generateEdgeToken(%d) = %s, want %s", unixSeconds, got, want)
		}
	}
}
